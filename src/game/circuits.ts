export function zoneInWorld(distance: number, world: WorldDef): Zone {
  const [first, second, third] = world.thresholds;
  if (distance > third) return world.zones[3];
  if (distance > second) return world.zones[2];
  if (distance > first) return world.zones[1];
  return world.zones[0];
}
